r"""Two transverse shear moduli and the torsional stiffness of BeamProp

``BeamProp.G12`` and ``BeamProp.G13`` are the transverse shear moduli of the
element planes `xy` and `xz`, and ``BeamProp.GJ`` the torsional stiffness.
Until they are set they follow ``G``: ``G12 = G13 = G`` and ``GJ = G*J``.

1. A property that sets only ``G`` gives the matrices and internal forces of
   pyfe3d 0.10.x: the arrays of ``tests/data/beam_single_G_reference.npz``
   were written with pyfe3d before ``G12``, ``G13`` and ``GJ`` existed, by
   :func:`element_arrays` with the inputs stored in the same file. On
   Windows, where the file was written, they are reproduced bit by bit,
   except the internal forces of BeamLR, which agree to round-off: their
   lines, generated by ``derive_beamLR_fint.py``, group the terms
   differently, e.g. ``G12``, ``G13`` and ``GJ`` multiply separate terms of
   the torsional rows, where ``G`` was a common factor. On other platforms
   the compiler may contract products and sums differently, hence a
   tolerance of round-off.
2. One element of BeamC gives the exact tip deflection of a cantilever with
   shear deformation, ``P*L**3/(3*E*I) + P*L/(G*A)``, Eq. (1.2) of Bathe,
   K. J., Finite Element Procedures, 1996, Section 1.2, p. 5, in each
   plane with its own modulus: ``Izz`` and ``G12`` for the deflection `v`,
   ``Iyy`` and ``G13`` for `w`. BeamLR converges to the same values.
3. The frequency coefficients of the cantilever of Example 3.10 and Table
   3.6 of Petyt, M., Introduction to Finite Element Vibration Analysis, 2nd
   ed., Cambridge University Press, 2010,
   https://doi.org/10.1017/CBO9780511761195, are obtained in the plane whose
   modulus is that of Petyt, whatever the modulus of the other plane.
4. The twist of a cantilever under a tip torque is ``T*L/GJ`` for any
   ``G12`` and ``G13``.
"""
import copy
import os
import pickle
import sys
sys.path.append('..')

import numpy as np
import pytest
from scipy.linalg import eigh
from scipy.sparse import coo_matrix

from pyfe3d.beamprop import BeamProp
from pyfe3d import (BeamC, BeamCData, BeamCProbe, BeamLR, BeamLRData,
                    BeamLRProbe, Truss, TrussData, TrussProbe, DOF, INT,
                    DOUBLE)

ELEMENTS = {
    'BeamC': (BeamC, BeamCData, BeamCProbe),
    'BeamLR': (BeamLR, BeamLRData, BeamLRProbe),
    'Truss': (Truss, TrussData, TrussProbe),
}
REFERENCE = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data',
                         'beam_single_G_reference.npz')


def general_prop():
    """Property with every attribute non-zero, the beam axis off the
    centroid"""
    p = BeamProp()
    p.A = 0.0032
    p.E = 71.e9
    p.G = 26.e9
    p.Iyy = 2.1e-6
    p.Izz = 3.7e-6
    p.Iyz = 0.4e-6
    p.J = 1.3e-6
    p.Ay = 0.9e-5
    p.Az = -0.6e-5
    p.intrho = 8.6
    p.intrhoy = 0.024
    p.intrhoz = -0.016
    p.intrhoy2 = 0.012
    p.intrhoz2 = 0.0072
    p.intrhoyz = 0.0011
    return p


def element_arrays(name, prop, ncoords, u):
    """Matrices and internal forces of one element in a generic orientation

    The element joins the nodes 0 and 1 of ``ncoords``, the displacements
    ``u`` are those of the two nodes. Returns a dictionary with the values of
    the sparse matrices and the internal forces.
    """
    cls, datacls, probecls = ELEMENTS[name]
    data = datacls()
    probe = probecls()
    elem = cls(probe)
    elem.n1, elem.n2 = 0, 1
    elem.c1, elem.c2 = 0, DOF
    if name == 'Truss':
        elem.update_rotation_matrix(ncoords)
    else:
        elem.update_rotation_matrix(0.3, 1., -0.2, ncoords)
    elem.update_probe_xe(ncoords)
    elem.update_probe_ue(u)
    out = {}

    def sparse(method, size, *args):
        r = np.zeros(size, dtype=INT)
        c = np.zeros(size, dtype=INT)
        v = np.zeros(size, dtype=DOUBLE)
        method(r, c, v, prop, *args)
        return v

    out['KC0v'] = sparse(elem.update_KC0, data.KC0_SPARSE_SIZE)
    out['M0v'] = sparse(elem.update_M, data.M_SPARSE_SIZE, 0)
    out['M1v'] = sparse(elem.update_M, data.M_SPARSE_SIZE, 1)
    if name == 'Truss':
        elem.update_probe_finte(prop)
        out['finte'] = np.asarray(probe.finte).copy()
        fint = np.zeros(2*DOF)
        elem.update_fint(fint, prop)
        out['fint'] = fint
        return out
    out['KGv'] = sparse(elem.update_KG, data.KG_SPARSE_SIZE)
    out['KCNLv'] = sparse(elem.update_KCNL, data.KCNL_SPARSE_SIZE)
    for nonlinear in [0, 1]:
        elem.update_probe_finte(prop, nonlinear)
        out['finte%d' % nonlinear] = np.asarray(probe.finte).copy()
        fint = np.zeros(2*DOF)
        elem.update_fint(fint, prop, nonlinear)
        out['fint%d' % nonlinear] = fint
    return out


def reference_arrays(prop):
    """Inputs and arrays of the three elements

    ``tests/data/beam_single_G_reference.npz`` was written with pyfe3d
    0.10.x as ``np.savez(REFERENCE, **reference_arrays(general_prop()))``.
    """
    ncoords = np.array([0.1, -0.2, 0.05, 0.9, 0.35, -0.4])
    u = np.array([1.2e-3, -0.7e-3, 2.1e-3, 0.03, -0.02, 0.025,
                  -0.4e-3, 1.5e-3, -1.1e-3, -0.015, 0.035, -0.01])
    arrays = {'ncoords': ncoords, 'u': u}
    for name in ELEMENTS:
        for key, value in element_arrays(name, prop, ncoords, u).items():
            arrays['%s_%s' % (name, key)] = value
    return arrays


@pytest.mark.parametrize('explicit', [False, True])
def test_single_G_reference(explicit):
    ref = np.load(REFERENCE)
    prop = general_prop()
    if explicit:
        prop.G12 = prop.G
        prop.G13 = prop.G
        prop.GJ = prop.G*prop.J
    arrays = reference_arrays(prop)
    assert sorted(arrays) == sorted(ref.files)
    for key, value in arrays.items():
        exact = sys.platform == 'win32' and not key.startswith('BeamLR_fint')
        rtol = 0. if exact else 1e-13
        expected = ref[key]
        atol = rtol*abs(expected).max()
        np.testing.assert_allclose(value, expected, rtol=rtol, atol=atol,
                                   err_msg=key)
    # NOTE the explicit values give exactly the arrays of the defaults
    arrays_default = reference_arrays(general_prop())
    for key, value in arrays.items():
        assert np.array_equal(value, arrays_default[key])


def test_defaults_follow_G():
    prop = BeamProp()
    assert prop.G12 == prop.G13 == prop.GJ == 0
    prop.G = 3.
    prop.J = 5.
    assert prop.G12 == 3. and prop.G13 == 3. and prop.GJ == 15.
    prop.G12 = 1.
    prop.G13 = 2.
    prop.GJ = 7.
    prop.G = 4.
    prop.J = 6.
    assert prop.G12 == 1. and prop.G13 == 2. and prop.GJ == 7.
    for prop2 in [pickle.loads(pickle.dumps(prop)), copy.deepcopy(prop)]:
        assert prop2.G12 == 1. and prop2.G13 == 2. and prop2.GJ == 7.
        assert prop2.G == 4. and prop2.J == 6.
    del prop.G12
    del prop.G13
    del prop.GJ
    assert prop.G12 == 4. and prop.G13 == 4. and prop.GJ == 24.


def section_prop(G12, G13):
    """Deep rectangular section, Iyy different from Izz"""
    E = 1.
    b, h = 0.6, 1.
    prop = BeamProp()
    prop.A = b*h
    prop.E = E
    prop.G = E/2.6
    prop.G12 = G12
    prop.G13 = G13
    prop.Izz = b*h**3/12
    prop.Iyy = h*b**3/12
    prop.J = 0.2
    return prop


def assemble(name, prop, L, num_elements, mass=False):
    cls, datacls, probecls = ELEMENTS[name]
    data = datacls()
    probe = probecls()
    x = np.linspace(0, L, num_elements + 1)
    ncoords = np.vstack((x, 0*x, 0*x)).T.flatten()
    N = DOF*(num_elements + 1)
    KC0r = np.zeros(data.KC0_SPARSE_SIZE*num_elements, dtype=INT)
    KC0c = np.zeros(data.KC0_SPARSE_SIZE*num_elements, dtype=INT)
    KC0v = np.zeros(data.KC0_SPARSE_SIZE*num_elements, dtype=DOUBLE)
    Mr = np.zeros(data.M_SPARSE_SIZE*num_elements, dtype=INT)
    Mc = np.zeros(data.M_SPARSE_SIZE*num_elements, dtype=INT)
    Mv = np.zeros(data.M_SPARSE_SIZE*num_elements, dtype=DOUBLE)
    for i in range(num_elements):
        elem = cls(probe)
        elem.init_k_KC0 = i*data.KC0_SPARSE_SIZE
        elem.init_k_M = i*data.M_SPARSE_SIZE
        elem.n1, elem.n2 = i, i + 1
        elem.c1, elem.c2 = DOF*i, DOF*(i + 1)
        if name == 'Truss':
            elem.update_rotation_matrix(ncoords)
        else:
            elem.update_rotation_matrix(0., 1., 0., ncoords)
        elem.update_probe_xe(ncoords)
        elem.update_KC0(KC0r, KC0c, KC0v, prop)
        if mass:
            elem.update_M(Mr, Mc, Mv, prop, 0)
    KC0 = coo_matrix((KC0v, (KC0r, KC0c)), shape=(N, N)).toarray()
    M = coo_matrix((Mv, (Mr, Mc)), shape=(N, N)).toarray()
    return KC0, M


def cantilever_tip(name, prop, L, num_elements, dof):
    """Tip displacement of the dof ``dof`` under a unit load on the same
    dof, the node at x = 0 clamped; only the dof ``dof`` of each node for
    the Truss, which has no bending stiffness"""
    KC0, _ = assemble(name, prop, L, num_elements)
    N = KC0.shape[0]
    bu = np.ones(N, dtype=bool)
    if name == 'Truss':
        bu[:] = False
        bu[dof::DOF] = True
    bu[:DOF] = False
    f = np.zeros(N)
    f[N - DOF + dof] = 1.
    u = np.zeros(N)
    u[bu] = np.linalg.solve(KC0[np.ix_(bu, bu)], f[bu])
    return u[N - DOF + dof]


@pytest.mark.parametrize('name, num_elements, rtol', [
    ('BeamC', 1, 1e-10),
    ('BeamLR', 200, 1e-4),
    ])
@pytest.mark.parametrize('G12, G13', [(0.4, 0.1), (0.1, 0.4)])
def test_cantilever_two_shear_moduli(name, num_elements, rtol, G12, G13):
    L = 1.
    prop = section_prop(G12, G13)
    # NOTE Eq. (1.2) of Bathe (1996) in each plane, with its own modulus
    v_ref = L**3/(3*prop.E*prop.Izz) + L/(G12*prop.A)
    w_ref = L**3/(3*prop.E*prop.Iyy) + L/(G13*prop.A)
    v = cantilever_tip(name, prop, L, num_elements, 1)
    w = cantilever_tip(name, prop, L, num_elements, 2)
    print(name, v, v_ref, w, w_ref)
    assert np.isclose(v, v_ref, rtol=rtol)
    assert np.isclose(w, w_ref, rtol=rtol)
    # NOTE the shear deflection is a large part, the modulus of the other
    #      plane gives a different value
    assert not np.isclose(v, L**3/(3*prop.E*prop.Izz) + L/(G13*prop.A),
                          rtol=0.1)


@pytest.mark.parametrize('name', list(ELEMENTS))
def test_torsion_given_GJ(name):
    L = 2.
    num_elements = 4
    twist = []
    for G12, G13 in [(0.4, 0.1), (0.1, 0.4), (1., 1.)]:
        prop = section_prop(G12, G13)
        prop.GJ = 0.05
        rx = cantilever_tip(name, prop, L, num_elements, 3)
        assert np.isclose(rx, L/prop.GJ, rtol=1e-12)
        twist.append(rx)
    assert twist[0] == twist[1] == twist[2]
    # NOTE GJ not set, G*J
    prop = section_prop(0.4, 0.1)
    rx = cantilever_tip(name, prop, L, num_elements, 3)
    assert np.isclose(rx, L/(prop.G*prop.J), rtol=1e-12)


def petyt_prop(plane, other):
    """Section of Example 3.10 of Petyt (2010), r/L = 0.08, kappa = 2/3,
    E/G = 8/3, with kappa*G in the plane ``plane`` and ``other`` times
    kappa*G in the other plane"""
    L = 1.
    E = 1.
    rho = 1.
    A = 1.
    kappa = 2/3
    G = 3/8*E
    I = (0.08*L)**2*A
    prop = BeamProp()
    prop.A = A
    prop.E = E
    prop.G = G
    prop.G12 = kappa*G*(1. if plane == 'xy' else other)
    prop.G13 = kappa*G*(1. if plane == 'xz' else other)
    prop.Izz = prop.Iyy = I
    prop.J = 2*I
    prop.intrho = rho*A
    prop.intrhoy2 = rho*I
    prop.intrhoz2 = rho*I
    return prop


def petyt_coefficients(name, plane, other, num_elements, num_modes,
                       prop_plane=None):
    """Frequency coefficients omega*sqrt(rho*A*L**4/(E*I)) of the bending in
    ``plane``, the node at x = 0 clamped, with the modulus of Petyt in
    ``prop_plane``, by default ``plane``"""
    prop = petyt_prop(plane if prop_plane is None else prop_plane, other)
    K, M = assemble(name, prop, 1., num_elements, mass=True)
    N = K.shape[0]
    # NOTE v and r_z for xy, w and r_y for xz, of the free nodes
    bu = np.zeros(N, dtype=bool)
    dofs = (1, 5) if plane == 'xy' else (2, 4)
    for dof in dofs:
        bu[DOF + dof::DOF] = True
    eigvals = eigh(K[np.ix_(bu, bu)], M[np.ix_(bu, bu)], eigvals_only=True)
    omega = np.sqrt(eigvals[:num_modes])
    return omega*np.sqrt(prop.intrho/(prop.E*prop.Izz))


@pytest.mark.parametrize('plane', ['xy', 'xz'])
def test_petyt_frequencies_two_shear_moduli(plane):
    for other in [0.25, 4.]:
        # NOTE one element, Example 3.10 of Petyt (2010), p. 99-100,
        #      published with three decimals
        coef = petyt_coefficients('BeamC', plane, other, 1, 2)
        print(plane, other, coef)
        assert np.allclose(coef, [3.322, 26.569], atol=0.0005, rtol=0)
        # NOTE exact values of Table 3.6 of Petyt (2010), see
        #      tests/test_timoshenko_beam_literature.py
        coef = petyt_coefficients('BeamLR', plane, other, 640, 3)
        print(plane, other, coef)
        assert np.allclose(coef, [3.284, 15.488, 34.301], rtol=1e-4)
    # NOTE with the modulus of Petyt in the other plane, the values change
    coef = petyt_coefficients('BeamC', plane, 0.25, 1, 2,
                              prop_plane='xz' if plane == 'xy' else 'xy')
    print(plane, coef)
    assert not np.allclose(coef, [3.322, 26.569], atol=0.01, rtol=0)


def element_matrices(name, prop):
    """KC0, KG and M, dense, of one element along the global x axis, with an
    axial force"""
    cls, datacls, probecls = ELEMENTS[name]
    data = datacls()
    elem = cls(probecls())
    elem.c1, elem.c2 = 0, DOF
    ncoords = np.array([0., 0., 0., 1.5, 0., 0.])
    elem.update_rotation_matrix(0., 1., 0., ncoords)
    elem.update_probe_xe(ncoords)
    u = np.zeros(2*DOF)
    u[DOF] = -1.e-3
    u[1], u[DOF + 5] = 2.e-3, 1.e-3
    u[2], u[DOF + 4] = -1.e-3, 3.e-3
    elem.update_probe_ue(u)
    out = []
    for method, size in [(elem.update_KC0, data.KC0_SPARSE_SIZE),
                         (elem.update_KG, data.KG_SPARSE_SIZE),
                         (elem.update_M, data.M_SPARSE_SIZE)]:
        r = np.zeros(size, dtype=INT)
        c = np.zeros(size, dtype=INT)
        v = np.zeros(size, dtype=DOUBLE)
        method(r, c, v, prop)
        out.append(coo_matrix((v, (r, c)), shape=(2*DOF, 2*DOF)).toarray())
    return out


@pytest.mark.parametrize('name', ['BeamC', 'BeamLR'])
def test_planes_use_own_modulus(name):
    """With a centroidal principal axis the two planes of bending are
    uncoupled: the entries of v, r_z are those of a single modulus G12 and
    the entries of w, r_y those of a single modulus G13, in KC0, KG and M"""
    prop = section_prop(0.4, 0.1)
    prop.intrho = 1.
    prop.intrhoy2 = 0.2
    prop.intrhoz2 = 0.1
    xy = [1, 5, DOF + 1, DOF + 5]
    xz = [2, 4, DOF + 2, DOF + 4]
    two = element_matrices(name, prop)
    for G, dofs in [(0.4, xy), (0.1, xz)]:
        single = section_prop(G, G)
        del single.G12
        del single.G13
        single.G = G
        single.intrho = prop.intrho
        single.intrhoy2 = prop.intrhoy2
        single.intrhoz2 = prop.intrhoz2
        for A, B in zip(two, element_matrices(name, single)):
            assert np.array_equal(A[np.ix_(dofs, dofs)], B[np.ix_(dofs, dofs)])
            assert np.any(A[np.ix_(dofs, dofs)] != 0)


@pytest.mark.parametrize('name', ['BeamC', 'BeamLR'])
def test_finte_KC0_two_shear_moduli(name):
    """The linear internal forces are KC0 u with G12, G13 and GJ set and an
    offset axis, which couples the shear strains and the twist"""
    ref = np.load(REFERENCE)
    prop = general_prop()
    prop.G12 = 31.e9
    prop.G13 = 17.e9
    prop.GJ = 0.4*prop.G*prop.J
    cls, datacls, probecls = ELEMENTS[name]
    data = datacls()
    arrays = element_arrays(name, prop, ref['ncoords'], ref['u'])
    probe = probecls()
    elem = cls(probe)
    elem.c1, elem.c2 = 0, DOF
    elem.update_rotation_matrix(0.3, 1., -0.2, ref['ncoords'])
    elem.update_probe_xe(ref['ncoords'])
    KC0r = np.zeros(data.KC0_SPARSE_SIZE, dtype=INT)
    KC0c = np.zeros(data.KC0_SPARSE_SIZE, dtype=INT)
    KC0v = np.zeros(data.KC0_SPARSE_SIZE, dtype=DOUBLE)
    elem.update_KC0(KC0r, KC0c, KC0v, prop)
    KC0 = coo_matrix((KC0v, (KC0r, KC0c)), shape=(2*DOF, 2*DOF)).toarray()
    assert np.allclose(KC0, KC0.T, rtol=0, atol=1e-12*abs(KC0).max())
    fint = KC0 @ ref['u']
    assert np.allclose(arrays['fint0'], fint, rtol=0,
                       atol=1e-12*abs(fint).max())
    # NOTE the arrays differ from those of a single modulus
    arrays_G = element_arrays(name, general_prop(), ref['ncoords'],
                              ref['u'])
    assert not np.allclose(arrays['KC0v'], arrays_G['KC0v'])


